# ---------- перевірки ----------
errs = []
for g in GROUPS:
    assert len(g['h']) == 15 and len(g['d']) == 4, g['name']
    for h in g['h']:
        if len(h) > 30: errs.append(('H', len(h), h))
    for d in g['d']:
        if len(d) > 90: errs.append(('D', len(d), d))
    for p in (g['p1'], g['p2']):
        if len(p) > 15: errs.append(('P', p))
    if len(set(g['h'])) != 15: errs.append(('dup', g['name']))
for c in CALLOUTS:
    if len(c) > 25: errs.append(('C', len(c), c))
for s in SITELINKS:
    if len(s[0]) > 25 or len(s[1]) > 35 or len(s[2]) > 35: errs.append(('S', s))
for v in SNIPPET[1]:
    if len(v) > 25: errs.append(('SN', v))
if errs:
    print('\n'.join(map(str, errs))); sys.exit(1)

# ---------- CSV для Google Ads Editor ----------
H = ['Campaign', 'Campaign Type', 'Networks', 'Budget', 'Budget type', 'Bid Strategy Type', 'Languages', 'Location',
     'Campaign Status', 'Ad Group', 'Ad Group Status', 'Keyword', 'Criterion Type', 'Ad type', 'Final URL', 'Path 1', 'Path 2'] + \
    ['Headline %d' % i for i in range(1, 16)] + ['Description %d' % i for i in range(1, 5)] + ['Status']
rows = []
def row(**k):
    r = {h: '' for h in H}; r.update(k); rows.append(r)
row(Campaign=CAMP, **{'Campaign Type': 'Search', 'Networks': 'Google search', 'Budget': BUDGET, 'Budget type': 'Daily',
    'Bid Strategy Type': 'Maximize clicks', 'Languages': 'Ukrainian;Russian', 'Location': 'Ukraine', 'Campaign Status': 'Paused'})
for g in GROUPS:
    row(Campaign=CAMP, **{'Ad Group': g['name'], 'Ad Group Status': 'Enabled'})
    for kw in g['kw']:
        for mt in ('Phrase', 'Exact'):
            row(Campaign=CAMP, **{'Ad Group': g['name'], 'Keyword': kw, 'Criterion Type': mt, 'Status': 'Enabled'})
    ad = {'Ad Group': g['name'], 'Ad type': 'Responsive search ad', 'Final URL': g['url'], 'Path 1': g['p1'], 'Path 2': g['p2'], 'Status': 'Enabled'}
    for i, h in enumerate(g['h'], 1): ad['Headline %d' % i] = h
    for i, d in enumerate(g['d'], 1): ad['Description %d' % i] = d
    row(Campaign=CAMP, **ad)
for n in NEG:
    row(Campaign=CAMP, **{'Keyword': n, 'Criterion Type': 'Campaign Negative Phrase', 'Status': 'Enabled'})

with open('google-ads-editor-import.csv', 'w', newline='', encoding='utf-8-sig') as f:
    w = csv.DictWriter(f, fieldnames=H); w.writeheader(); w.writerows(rows)

json.dump({'groups': GROUPS, 'neg': NEG, 'callouts': CALLOUTS, 'sitelinks': SITELINKS, 'snippet': SNIPPET},
          open('ads.json', 'w'), ensure_ascii=False, indent=1)
print('ok rows', len(rows), 'keywords', sum(len(g['kw']) for g in GROUPS))
